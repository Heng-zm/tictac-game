import type { AppConfigPayload } from '../../shared/game-types';

type InviteConfig = Pick<AppConfigPayload, 'botUsername' | 'miniAppUrl'>;

const PRIVATE_IPV4_PATTERN =
  /^(?:10(?:\.\d{1,3}){3}|127(?:\.\d{1,3}){3}|169\.254(?:\.\d{1,3}){2}|172\.(?:1[6-9]|2\d|3[01])(?:\.\d{1,3}){2}|192\.168(?:\.\d{1,3}){2})$/;

function isLocalOrPrivateHost(hostname: string): boolean {
  return (
    hostname === 'localhost' ||
    hostname.endsWith('.localhost') ||
    hostname.endsWith('.local') ||
    hostname === '0.0.0.0' ||
    hostname === '::1' ||
    hostname === '[::1]' ||
    PRIVATE_IPV4_PATTERN.test(hostname)
  );
}

/**
 * A link generated by a local server often points at localhost:5173, which is
 * not reachable from the device that is viewing the app. When either the
 * configured URL or the generated link is local, prefer the current origin.
 */
export function alignInviteLinkToCurrentOrigin(
  link: string,
  config: InviteConfig | null,
  currentOrigin: string,
): string {
  if (config?.botUsername) return link;
  try {
    const url = new URL(link);
    if (url.hostname === 't.me' || url.hostname === 'telegram.me') return link;
    const current = new URL(currentOrigin);
    if (url.origin === current.origin) return link;

    const configured = config?.miniAppUrl ? new URL(config.miniAppUrl) : null;
    const configuredIsLocal = configured ? isLocalOrPrivateHost(configured.hostname) : false;
    const linkIsLocal = isLocalOrPrivateHost(url.hostname);
    if (!configuredIsLocal && !linkIsLocal) return link;

    const target = new URL(current.origin);
    target.pathname = url.pathname;
    target.search = url.search;
    target.hash = url.hash;
    return target.toString();
  } catch {
    return link;
  }
}

export function buildInviteDeepLink(
  config: InviteConfig | null,
  token: string,
  currentOrigin = typeof window === 'undefined' ? '' : window.location.origin,
): string {
  const startParam = `invite_${token}`;
  if (config?.botUsername) {
    return `https://t.me/${config.botUsername}?startapp=${encodeURIComponent(startParam)}`;
  }
  const base = config?.miniAppUrl ?? currentOrigin;
  try {
    const url = new URL(base);
    url.searchParams.set('startapp', startParam);
    return alignInviteLinkToCurrentOrigin(url.toString(), config, currentOrigin);
  } catch {
    const fallbackOrigin = currentOrigin || 'http://localhost:5173';
    return `${fallbackOrigin}/?startapp=${encodeURIComponent(startParam)}`;
  }
}

export function isValidInviteToken(token: string): boolean {
  return /^[A-Za-z0-9_-]{43}$/.test(token);
}
